def scheme_for_method(method_id: str) -> SchemeConfig:
    method_id = method_id.lower()
    if method_id == "proposed":
        return SchemeConfig(
            name="cp7_proposed",
            robust_communication=True,
            chance_sensing=True,
            fixed_trajectory=False,
            sensing_mode="optimized",
        )
    if method_id == "deterministic_joint":
        return SchemeConfig(
            name="cp7_adapted_deterministic_joint",
            robust_communication=False,
            chance_sensing=False,
            fixed_trajectory=False,
            sensing_mode="optimized",
        )
    if method_id == "trajectory_fixed_sensing":
        return SchemeConfig(
            name="cp7_adapted_trajectory_fixed_sensing20",
            robust_communication=False,
            chance_sensing=False,
            fixed_trajectory=False,
            sensing_mode="fixed_fraction",
            sensing_fraction=0.20,
        )
    if method_id == "robust_fixed_geometry":
        return SchemeConfig(
            name="cp7_adapted_robust_fixed_geometry",
            robust_communication=True,
            chance_sensing=True,
            fixed_trajectory=True,
            sensing_mode="optimized",
        )
    raise ValueError(f"Unsupported CP7 method_id={method_id!r}")


def _s9_topology(base: SimulationConfig, seed: int) -> tuple[str, SimulationConfig]:
    if seed == 0:
        cfg = deepcopy(base)
        cfg.topology_seed = 0
        return "T0_locked_geometry", cfg
    frozen = S9_FROZEN_TOPOLOGIES[seed]
    cfg = deepcopy(base)
    cfg.mission.users_m = [list(row) for row in frozen["users_m"]]
    cfg.mission.targets_initial = [list(row) for row in frozen["targets_initial"]]
    cfg.topology_seed = seed
    return f"T{1 if seed == 10_000 else 2}_seed{seed}", cfg


def build_s9_plan(base: SimulationConfig) -> list[PlannedExperiment]:
    """Three topology identities x four adapted mechanisms = 12 configurations."""
    plan: list[PlannedExperiment] = []
    for seed in S9_TOPOLOGY_SEEDS:
        topology_label, topo_cfg = _s9_topology(base, seed)
        for method_id in S9_METHOD_IDS:
            cfg = deepcopy(topo_cfg)
            cfg.scenario = "S9"
            cfg.scheme = scheme_for_method(method_id)
            # Same random seed across methods in one topology gives common Monte-Carlo
            # audit draws.  The topology identity is carried separately by topology_seed.
            cfg.solver.random_seed = base.solver.random_seed
            plan.append(
                PlannedExperiment(
                    experiment="S9",
                    method_id=method_id,
                    topology_label=topology_label,
                    topology_seed=seed,
                    pcrb_threshold_m2=float(cfg.physical.pcrb_threshold_m2),
                    mobility_mode="fixed" if cfg.scheme.fixed_trajectory else "mobile",
                    config=cfg,
                )
            )
    return plan


def _s5b_geometry(base: SimulationConfig) -> SimulationConfig:
    cfg = deepcopy(base)
    cfg.scenario = "S5B"
    cfg.topology_seed = 0
    cfg.mission.q_initial_m = list(S5B_Q_HOVER_M)
    cfg.mission.q_final_m = list(S5B_Q_HOVER_M)
    cfg.mission.v_initial_mps = [0.0, 0.0, 0.0]
    cfg.mission.v_final_mps = [0.0, 0.0, 0.0]
    cfg.mission.users_m = [list(x) for x in S5B_USERS_M]
    cfg.mission.targets_initial = [list(x) for x in S5B_TARGETS_INITIAL]

    # Match the already-locked S5A y260 trajectory-search budget.  This is not tuned
    # per PCRB threshold; every S5B pair uses the same trajectory-search settings.
    cfg.solver.outer_iterations = 5
    cfg.solver.trajectory_control_segments = 6
    cfg.solver.trajectory_multistart = 4
    cfg.solver.trajectory_probe_scale = 0.35
    cfg.solver.trajectory_trust_accel_mps2 = 1.0
    return cfg


def build_s5b_plan(base: SimulationConfig) -> list[PlannedExperiment]:
    """Hard locked geometry x five PCRB thresholds x fixed/mobile = 10 configs."""
    seed_cfg = _s5b_geometry(base)
    plan: list[PlannedExperiment] = []
    for threshold in S5B_PCRB_THRESHOLDS_M2:
        for mobility_mode in S5B_MOBILITY_MODES:
            cfg = deepcopy(seed_cfg)
            cfg.physical.pcrb_threshold_m2 = float(threshold)
            if mobility_mode == "fixed_hover":
                cfg.scheme = SchemeConfig(
                    name=f"cp7_fixed_hover_pcrb{threshold:g}",
                    robust_communication=True,
                    chance_sensing=True,
                    fixed_trajectory=True,
                    sensing_mode="optimized",
                )
            else:
                cfg.scheme = SchemeConfig(
                    name=f"cp7_mobile_pcrb{threshold:g}",
                    robust_communication=True,
                    chance_sensing=True,
                    fixed_trajectory=False,
                    sensing_mode="optimized",
                )
            plan.append(
                PlannedExperiment(
                    experiment="S5B",
                    method_id="robust_fixed_hover" if mobility_mode == "fixed_hover" else "robust_mobile",
                    topology_label="S5A_y260_locked_geometry",
                    topology_seed=0,
                    pcrb_threshold_m2=float(threshold),
                    mobility_mode=mobility_mode,
                    config=cfg,
                )
            )
    return plan


def build_plan(base: SimulationConfig, experiments: Iterable[str]) -> list[PlannedExperiment]:
    plan: list[PlannedExperiment] = []
    for name in experiments:
        exp = name.upper()
        if exp == "S9":
            plan.extend(build_s9_plan(base))
        elif exp == "S5B":
            plan.extend(build_s5b_plan(base))
        else:
            raise ValueError(f"Unsupported CP7 experiment {name!r}; choose S9 and/or S5B")
    return plan
